#!/usr/bin/env node
/**
 * mcp-golden-labels — writes docs/mcp-golden/labels.json: the labels Studio's
 * own `renderer/labels` draws for a fixed set of label texts, every template ×
 * both resolutions, as SHA-256 of the SVG (and the full SVG of the classic one),
 * plus `qrSvg` for each link. The hosted connector's `get_label`
 * (TigerHub lib/labels/build.ts) checks its output against it, so a drift on
 * either side shows.
 *
 *   node scripts/mcp-golden-labels.mjs           — rewrite the file
 *   node scripts/mcp-golden-labels.mjs --check   — exit 1 when it is out of date
 *
 * Runs the renderer module under Node: `window.qrcode` is the vendored
 * qrcode-generator, `t` reads the en locale; buildLabel touches no DOM.
 */
import { createRequire } from "node:module";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "docs/mcp-golden/labels.json");
const require = createRequire(import.meta.url);
globalThis.window = { qrcode: require(path.join(ROOT, "renderer/lib/qrcode/qrcode.js")) };
globalThis.document = { getElementById: () => null };   // initLabels wires the card, absent here

const en = JSON.parse(readFileSync(path.join(ROOT, "renderer/locales/en.json"), "utf8"));
const t = (k) => (typeof en[k] === "string" ? en[k] : k);
const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

const labels = await import(path.join(ROOT, "renderer/labels/index.js"));
labels.initLabels({ t, esc });
const { buildLabel, qrSvg, LABEL_TEMPLATES, spoolLink, productLink } = labels;
const sha = (s) => createHash("sha256").update(s).digest("hex");

// Label texts as `labelInfo(row)` (renderer/inventory.js, initLabels) returns them.
const INFOS = [
  { id: "spool-tigertag-plus", kind: "spool", link: spoolLink("TigerData_17938000000001234"),
    info: { brand: "Rosa3D", protocol: "TigerQR+", series: "PLA Starter", material: "PLA", hexes: ["#00A86B"], name: "Jade White",
      values: { nozzle: "190–220 °C", bed: "50–60 °C", dry: "50 °C · 4 h", td: "2.4", diameter: "1.75 mm" } } },
  { id: "spool-chip-no-product", kind: "spool", link: spoolLink("04A1B2C3D4E5F6"),
    info: { brand: "Generic", protocol: "TigerQR", series: "", material: "PETG", hexes: ["#141418"], name: "Galaxy Black",
      values: { nozzle: "230–250 °C", bed: "70–80 °C", dry: "", td: "", diameter: "1.75 mm" } } },
  { id: "spool-multicolour", kind: "spool", link: spoolLink("TigerData_17938000000005678"),
    info: { brand: "Sunlu", protocol: "TigerQR+", series: "PLA Silk Rainbow & Co", material: "PLA", hexes: ["#FF0000", "#00FF00", "#0000FF"], name: "Rainbow <Tri>",
      values: { nozzle: "200–? °C", bed: "", dry: "45 °C", td: "", diameter: "" } } },
  { id: "product-filament-label", kind: "product", link: productLink(84213),
    info: { brand: "Rosa3D", protocol: "TigerQR+", series: "PLA Starter", material: "PLA", hexes: ["#00A86B"], name: "Jade White",
      values: { nozzle: "190–220 °C", bed: "50–60 °C", dry: "50 °C · 4 h", td: "", diameter: "1.75 mm" } } },
  { id: "spool-no-link", kind: "spool", link: null,
    info: { brand: "Prusament", protocol: "TigerQR", series: "", material: "ASA", hexes: ["#E04A1F"], name: "Prusa Orange",
      values: { nozzle: "", bed: "", dry: "", td: "", diameter: "" } } },
];
const SLOTS = [["nozzle", "bed", "dry", "td"], ["diameter", "td"], []];

const cases = [];
for (const c of INFOS) {
  for (const tpl of LABEL_TEMPLATES) {
    for (const dpi of [203, 300]) {
      for (const slots of tpl.slots ? SLOTS : [[]]) {
        const lbl = buildLabel(c.info, c.link, { template: tpl.id, slots, dpi });
        cases.push({ info_id: c.id, template: tpl.id, dpi, slots, mm: [lbl.mmW, lbl.mmH],
          svg_sha256: sha(lbl.svg), ...(tpl.id === "classic" && dpi === 203 && slots.length === 4 ? { svg: lbl.svg } : {}) });
      }
    }
  }
}
const links = [...new Set(INFOS.map((c) => c.link).filter(Boolean))].map((link) => ({ link, qr_svg_sha256: sha(qrSvg(link)) }));

const doc = {
  about: "Generated by scripts/mcp-golden-labels.mjs from renderer/labels/index.js — do not edit by hand. Slot words: the en locale (lbNozzle, lbBed, addProductDrying, labelSlotTd, detDiameter).",
  templates: LABEL_TEMPLATES,
  infos: INFOS,
  cases,
  qr: links,
};
const text = JSON.stringify(doc, null, 1) + "\n";
if (process.argv.includes("--check")) {
  let old = "";
  try { old = readFileSync(OUT, "utf8"); } catch (_) {}
  if (old !== text) { console.error("docs/mcp-golden/labels.json is out of date — run node scripts/mcp-golden-labels.mjs"); process.exit(1); }
  console.log(`labels golden OK (${cases.length} labels, ${links.length} QR codes)`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${cases.length} labels, ${links.length} QR codes`);
}
