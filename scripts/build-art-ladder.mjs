#!/usr/bin/env node
/**
 * build-art-ladder.mjs — the size ladder of the app's illustrations.
 *
 * Each master (a transparent PNG at least 1024 px wide, under assets-src/img/, listed in
 * LADDER_DIRS below) becomes four WebP renditions next to where the app reads it:
 *
 *   assets-src/img/tigersquad/squad-notice/tiger-back.png
 *     → assets/img/tigersquad/squad-notice/tiger-back-{128,256,512,1024}.webp
 *
 * and renderer/art-ladder.js (generated) records each picture's master size, so
 * artImg() (renderer/art.js) can give the <img> its proportions before it loads and
 * let Chromium pick the rendition that fits the rendered size × screen density
 * (srcset + sizes="auto"). A master narrower than 1024 px still gets every rendition
 * (upscaled) so no size is missing, and is reported: regenerate it bigger
 * (docs/ART-DIRECTION.md, "Size").
 *
 *   npm run art:build            # renditions out of date or missing only
 *   npm run art:build -- --force # all of them
 *   npm run art:check            # fails when a master has a rendition missing or is not indexed
 *                                  (existence only: a fresh clone resets the file dates)
 */
import { readdirSync, statSync, existsSync, writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "assets-src/img");
const OUT = join(ROOT, "assets/img");
const INDEX = join(ROOT, "renderer/art-ladder.js");
export const WIDTHS = [128, 256, 512, 1024];
// Folders whose masters get the ladder (relative to assets-src/img/). Every *.png in
// them except the generated sheets (*-source.png).
const LADDER_DIRS = [
  "tigersquad/invite-hero",
  "tigersquad/squad-notice",
  "tigersquad/requests",
];

const args = process.argv.slice(2);
const force = args.includes("--force"), check = args.includes("--check");

const masters = LADDER_DIRS.flatMap(d => {
  const dir = join(SRC, d);
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter(f => f.endsWith(".png") && !f.endsWith("-source.png")).map(f => join(dir, f));
});

const sharp = check ? null : (await import("sharp")).default;
const index = {}, small = [], stale = [];
const indexed = existsSync(INDEX) ? new Set([...readFileSync(INDEX, "utf8").matchAll(/^\s+"([^"]+)":/gm)].map(m => m[1])) : new Set();
for (const src of masters) {
  const key = relative(SRC, src).replace(/\\/g, "/").replace(/\.png$/, "");
  const base = join(OUT, key);
  const outs = WIDTHS.map(w => `${base}-${w}.webp`);
  const mtime = statSync(src).mtimeMs;
  const fresh = outs.every(o => existsSync(o) && statSync(o).mtimeMs >= mtime);
  if (check) { if (!outs.every(o => existsSync(o)) || !indexed.has(key)) stale.push(key); continue; }
  const meta = await sharp(src).metadata();
  index[key] = [meta.width, meta.height];
  if (meta.width < WIDTHS.at(-1)) small.push(`${key} (${meta.width} px)`);
  if (fresh && !force) continue;
  mkdirSync(dirname(base), { recursive: true });
  for (const [i, w] of WIDTHS.entries()) {
    await sharp(src).resize({ width: w, kernel: "lanczos3" }).webp({ quality: 86, alphaQuality: 100, effort: 6 }).toFile(outs[i]);
  }
  console.log(`[art] ${key}  ${meta.width}×${meta.height} → ${WIDTHS.join(" / ")}`);
}

if (check) {
  if (stale.length) { console.error(`[art] renditions missing or picture not indexed — run npm run art:build:\n  ${stale.join("\n  ")}`); process.exit(1); }
  console.log(`[art] OK — ${masters.length} masters, every rendition present and indexed.`);
  process.exit(0);
}

const body = Object.keys(index).sort().map(k => `  "${k}": [${index[k].join(", ")}],`).join("\n");
writeFileSync(INDEX, `// GENERATED by scripts/build-art-ladder.mjs — do not edit. npm run art:build rewrites it.
// Each laddered picture (path under assets/img/, no extension) → its master's [width, height];
// renditions <key>-{${WIDTHS.join(",")}}.webp sit next to it. Read by renderer/art.js.
export const ART_WIDTHS = [${WIDTHS.join(", ")}];
export default {
${body}
};
`);
console.log(`[art] ${Object.keys(index).length} pictures indexed in renderer/art-ladder.js`);
if (small.length) console.warn(`[art] masters narrower than ${WIDTHS.at(-1)} px (upscaled — regenerate them bigger):\n  ${small.join("\n  ")}`);
